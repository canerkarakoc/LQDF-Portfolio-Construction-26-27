
"""
LQDF Portfolio Construction
Phase 3 - Operational Risk Controls

Review proposed orders generated by trade_orders.py.

This is a research demonstration only.
No live trades are placed or approved.

Thresholds are illustrative, not official LQDF limits.
"""

from pathlib import Path

import numpy as np
import pandas as pd


# --------------------------------------------------
# 1. Configuration
# --------------------------------------------------

ROOT = Path(__file__).resolve().parents[1]

INPUT_DIR = ROOT / "results" / "trade_orders"
OUTPUT_DIR = ROOT / "results" / "risk_controls"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

PORTFOLIO_NAV = 1_000_000.0

MAX_ASSET_WEIGHT = 0.60
MAX_TRADE_FRACTION = 0.10
MAX_MONTHLY_TURNOVER = 0.15

DOLLAR_TOLERANCE = 0.01
WEIGHT_TOLERANCE = 1e-8

ASSETS = ["VTI", "EFA", "AGG", "GLD", "VNQ"]
STRATEGIES = ["MVO", "HRP", "Equal_Weight"]


# --------------------------------------------------
# 2. Load simulated orders
# --------------------------------------------------

def load_data():

    orders = pd.read_csv(
        INPUT_DIR / "simulated_trade_orders.csv",
        parse_dates=["Date"]
    )

    summary = pd.read_csv(
        INPUT_DIR / "rebalance_summary.csv",
        parse_dates=["Date"]
    )

    required = {
        "Date", "Strategy", "Asset",
        "Current_Weight", "Target_Weight",
        "Weight_Change", "Side",
        "Trade_Value_USD", "Absolute_Trade_USD"
    }

    if not required.issubset(orders.columns):
        raise ValueError("Missing order columns.")

    if orders.empty or summary.empty:
        raise ValueError("Missing trading records.")

    if orders.duplicated(
        ["Date", "Strategy", "Asset"]
    ).any():
        raise ValueError("Duplicate order records.")

    return orders, summary


# --------------------------------------------------
# 3. Generate risk alerts
# --------------------------------------------------

def review_orders(orders, summary):

    alerts = []
    event_results = []

    def flag(date, strategy, category, asset,
             observed, threshold, explanation):

        alerts.append({
            "Date": date,
            "Strategy": strategy,
            "Risk_Category": category,
            "Asset": asset,
            "Observed_Value": observed,
            "Threshold": threshold,
            "Explanation": explanation
        })

    groups = orders.groupby(
        ["Date", "Strategy"], sort=True
    )

    for (date, strategy), group in groups:

        target = group["Target_Weight"].to_numpy(
            dtype=float
        )

        current = group["Current_Weight"].to_numpy(
            dtype=float
        )

        trades = group["Trade_Value_USD"].to_numpy(
            dtype=float
        )

        absolute = group["Absolute_Trade_USD"].to_numpy(
            dtype=float
        )

        # --------------------------------------
        # Check 1: Data and order integrity
        # --------------------------------------

        valid = (
            len(group) == len(ASSETS)
            and set(group["Asset"]) == set(ASSETS)
            and np.isfinite(target).all()
            and np.isfinite(current).all()
            and np.isfinite(trades).all()
            and np.isfinite(absolute).all()
        )

        if not valid:
            flag(
                date, strategy, "INVALID_DATA", "",
                np.nan, np.nan,
                "Missing assets or non-finite values."
            )

            event_results.append({
                "Date": date,
                "Strategy": strategy,
                "Status": "INVALID",
                "Alerts": 1
            })
            continue

        start_alerts = len(alerts)

        if (
            not np.isclose(
                target.sum(), 1.0,
                atol=WEIGHT_TOLERANCE
            )
            or not np.isclose(
                current.sum(), 1.0,
                atol=WEIGHT_TOLERANCE
            )
            or (target < -WEIGHT_TOLERANCE).any()
            or (current < -WEIGHT_TOLERANCE).any()
        ):
            flag(
                date, strategy, "INVALID_WEIGHTS", "",
                float(target.sum()), 1.0,
                "Invalid portfolio weights."
            )

        if not np.allclose(
            absolute, np.abs(trades),
            atol=DOLLAR_TOLERANCE
        ):
            flag(
                date, strategy, "ORDER_MISMATCH", "",
                np.nan, DOLLAR_TOLERANCE,
                "Absolute trade values do not match."
            )

        if not np.allclose(
            trades,
            (target - current) * PORTFOLIO_NAV,
            atol=DOLLAR_TOLERANCE
        ):
            flag(
                date, strategy, "ORDER_MISMATCH", "",
                np.nan, DOLLAR_TOLERANCE,
                "Trades do not match target changes."
            )

        expected_sides = np.where(
            trades > 1e-8, "BUY",
            np.where(trades < -1e-8, "SELL", "HOLD")
        )

        if not np.array_equal(
            group["Side"].to_numpy(),
            expected_sides
        ):
            flag(
                date, strategy, "ORDER_MISMATCH", "",
                np.nan, np.nan,
                "Order side does not match trade sign."
            )

        # --------------------------------------
        # Check 2: Excessive concentration
        # --------------------------------------

        for _, order in group.iterrows():

            if order["Target_Weight"] > MAX_ASSET_WEIGHT:

                flag(
                    date, strategy,
                    "CONCENTRATION",
                    order["Asset"],
                    float(order["Target_Weight"]),
                    MAX_ASSET_WEIGHT,
                    "Target asset weight exceeds 60%."
                )

            # ----------------------------------
            # Check 3: Large individual trades
            # ----------------------------------

            trade_fraction = (
                order["Absolute_Trade_USD"]
                / PORTFOLIO_NAV
            )

            if trade_fraction > MAX_TRADE_FRACTION:

                flag(
                    date, strategy,
                    "LARGE_TRADE",
                    order["Asset"],
                    float(trade_fraction),
                    MAX_TRADE_FRACTION,
                    "Individual trade exceeds 10% of NAV."
                )

        # --------------------------------------
        # Check 4: Monthly portfolio turnover
        # --------------------------------------

        turnover = float(
            np.abs(trades).sum()
            / (2.0 * PORTFOLIO_NAV)
        )

        if turnover > MAX_MONTHLY_TURNOVER:

            flag(
                date, strategy,
                "HIGH_TURNOVER", "",
                turnover,
                MAX_MONTHLY_TURNOVER,
                "Monthly one-way turnover exceeds 15%."
            )

        # --------------------------------------
        # Check 5: Buy/sell balance
        # --------------------------------------

        buys = float(trades[trades > 0].sum())
        sells = float(-trades[trades < 0].sum())

        imbalance = abs(buys - sells)

        if imbalance > DOLLAR_TOLERANCE:

            flag(
                date, strategy,
                "UNBALANCED_TRADES", "",
                imbalance,
                DOLLAR_TOLERANCE,
                "Proposed buys and sells do not balance."
            )

        new_alerts = len(alerts) - start_alerts

        event_results.append({
            "Date": date,
            "Strategy": strategy,
            "Status": (
                "REVIEW" if new_alerts else "PASS"
            ),
            "Alerts": new_alerts,
            "Largest_Target_Weight": float(
                target.max()
            ),
            "Largest_Trade_USD": float(
                absolute.max()
            ),
            "One_Way_Turnover": turnover
        })

    return (
        pd.DataFrame(alerts),
        pd.DataFrame(event_results)
    )


# --------------------------------------------------
# 4. Main execution
# --------------------------------------------------

def main():

    print("LQDF - Operational Risk Controls")
    print("--------------------------------")

    orders, summary = load_data()

    alerts, events = review_orders(
        orders, summary
    )

    assert len(events) == len(summary)
    assert len(events) == 423

    if not alerts.empty:
        alerts.to_csv(
            OUTPUT_DIR / "risk_alerts.csv",
            index=False
        )
    else:
        pd.DataFrame(columns=[
            "Date", "Strategy", "Risk_Category",
            "Asset", "Observed_Value",
            "Threshold", "Explanation"
        ]).to_csv(
            OUTPUT_DIR / "risk_alerts.csv",
            index=False
        )

    events.to_csv(
        OUTPUT_DIR / "risk_review_summary.csv",
        index=False
    )

    print("\nRebalance events reviewed:", len(events))
    print("Order records reviewed:", len(orders))

    print("\nEvent status:")
    print(events["Status"].value_counts().to_string())

    if not alerts.empty:

        print("\nAlerts by category:")
        print(
            alerts["Risk_Category"]
            .value_counts().to_string()
        )

        print("\nAlerts by strategy:")
        print(
            alerts.groupby("Strategy")
            .size().to_string()
        )

        print("\nFirst 10 alerts:")
        print(
            alerts[
                ["Date", "Strategy",
                 "Risk_Category", "Asset"]
            ].head(10).to_string(index=False)
        )
    else:
        print("\nNo risk alerts identified.")

    print("\nResults saved to:")
    print(OUTPUT_DIR)

    print(
        "\nPASS: Risk screening process completed."
    )

    if (events["Status"] == "INVALID").any():
        print(
            "WARNING: Invalid records require investigation."
        )


if __name__ == "__main__":
    main()
